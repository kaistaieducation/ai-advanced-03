# 준비 : 문의 예제 생성 → 모델 구성 → 학습 → 기준선 준비
# ────────────────────────────────────────────────────────────────
def 준비(조용히=False):
    """교육용 문의 예제를 만들고 모델을 학습시킵니다. (실행에 수십 초 걸립니다)"""
    random.seed(_SEED)
    np.random.seed(_SEED)
    keras.utils.set_random_seed(_SEED)

    학습문의, 학습정답 = _문의만들기(_학습_핵심구, _학습_말끝)
    검증문의, 검증정답 = _문의만들기(_검증_핵심구, _평가_말끝)
    평가문의, 평가정답 = _문의만들기(_평가_핵심구, _평가_말끝)

    # 시연에 쓰는 두 문장이 학습·검증에 섞이지 않았는지 확인합니다.
    섞임 = [s for s in (문의A, 문의B) if s in set(학습문의) | set(검증문의)]
    if 섞임:  # pragma: no cover - 데이터 수정 시 안전장치
        raise RuntimeError("시연 문장이 학습/검증 데이터에 포함되어 있습니다: %s" % 섞임)

    문장벡터화 = keras.layers.TextVectorization(
        max_tokens=1000,
        standardize=None,
        split="character",
        output_sequence_length=_길이,
        name="text_vectorization")
    문장벡터화.adapt(학습문의)        # 사전은 학습 문의로만 만듭니다.

    def 숫자로(문장들):
        return 문장벡터화(tf.constant(list(문장들))).numpy()

    모델, 관찰모델 = _모델만들기(문장벡터화.vocabulary_size())
    모델.compile(optimizer="adam",
                 loss="sparse_categorical_crossentropy",
                 metrics=["accuracy"])
    기록 = 모델.fit(숫자로(학습문의), 학습정답,
                    validation_data=(숫자로(검증문의), 검증정답),
                    epochs=_학습횟수, batch_size=_묶음크기, verbose=0)

    # 기준선 — 겹치는 글자 조각이 많을수록 관련 있다고 보는 단순한 방식입니다.
    안내문_문장 = [t + " " + 내용 for t, 내용 in 안내문]
    키워드변환기 = TfidfVectorizer(analyzer="char_wb",
                                   ngram_range=(2, 3)).fit(안내문_문장 + 학습문의)
    안내문_키워드 = 키워드변환기.transform(안내문_문장)

    _상태.update(
        준비됨=True,
        숫자로=숫자로,
        모델=모델,
        관찰모델=관찰모델,
        기록=기록,
        학습문의=학습문의, 학습정답=학습정답,
        검증문의=검증문의, 검증정답=검증정답,
        평가문의=평가문의, 평가정답=평가정답,
        키워드변환기=키워드변환기,
        안내문_키워드=안내문_키워드,
    )

    if not 조용히:
        print("준비 완료")
        print("— 교육용 문의 예제로 연습을 마쳤습니다.")
        print()
        print("연습에 사용한 문의 예시")
        print("  " + 학습문의[0])
        print("  " + 학습문의[33])
        print()
        print("연습에 쓰지 않고 남겨 둔 문의도 따로 준비되어 있습니다.")
    return None


def _확인됨():
    if not _상태["준비됨"]:
        raise RuntimeError("먼저 준비() 를 실행해 주세요.")


