# ────────────────────────────────────────────────────────────────
# 데이터 만들기
# ────────────────────────────────────────────────────────────────
def _문의만들기(핵심구모음, 말끝모음):
    문장, 정답 = [], []
    for 라벨, 목록 in 핵심구모음.items():
        for 유형, 구 in 목록:
            if 유형 == "s":
                문장.append(구)
                정답.append(라벨)
                continue
            for 끝 in 말끝모음[유형]:
                문장.append(구 + " " + 끝)
                정답.append(라벨)
    return 문장, np.array(정답)


# ────────────────────────────────────────────────────────────────
# 모델 만들기
#   Embedding → 위치 표현 더하기 → Self-Attention → Add & Norm
#   → FFN(64→128→64) → Add & Norm → (padding 제외 평균) → 안내문 6종 점수
# ────────────────────────────────────────────────────────────────
def _모델만들기(사전크기):
    문의입력 = keras.Input(shape=(_길이,), dtype="int32", name="inquiry")

    # padding(0) 이 아닌 자리만 True 인 mask. 이 mask 를 두 곳에 직접 넣습니다.
    유효 = keras.ops.not_equal(문의입력, 0)                       # (batch, 길이)

    글자표현 = keras.layers.Embedding(사전크기, _폭, name="char_embedding")(문의입력)

    # 학습되는 위치 표현(learned positional embedding).
    # 2017 Original Transformer 의 sin·cos positional encoding 과는 다른 방식입니다.
    위치표현 = keras.layers.Embedding(_길이, _폭, name="position_embedding")(
        keras.ops.arange(_길이))
    위치포함 = 글자표현 + 위치표현

    # Self-Attention 이 padding 자리를 key/value 로 참고하지 못하도록 차단합니다.
    # (batch, 질의자리, 참고자리) 형태로 만들어 넘깁니다.
    참고가능 = keras.ops.repeat(keras.ops.expand_dims(유효, axis=1), _길이, axis=1)

    어텐션결과, 어텐션점수 = keras.layers.MultiHeadAttention(
        num_heads=_헤드수, key_dim=_폭 // _헤드수, dropout=0.1, name="self_attention"
    )(위치포함, 위치포함, attention_mask=참고가능, return_attention_scores=True)

    정리1 = keras.layers.LayerNormalization(name="add_norm_1")(위치포함 + 어텐션결과)

    # FFN — 중간에서 더 넓은 표현으로 바꾼 뒤 다시 원래 폭으로 되돌립니다.
    전달결과 = keras.layers.Dense(_FFN폭, activation="relu", name="ffn_expand")(정리1)
    전달결과 = keras.layers.Dense(_폭, name="ffn_project")(전달결과)

    인코더출력 = keras.layers.LayerNormalization(name="add_norm_2")(정리1 + 전달결과)

    # 문장 전체 표현 — padding 자리를 평균에서 제외한 평균입니다.
    가중치 = keras.ops.expand_dims(keras.ops.cast(유효, "float32"), axis=-1)
    합계 = keras.ops.sum(인코더출력 * 가중치, axis=1)
    유효자리수 = keras.ops.maximum(keras.ops.sum(가중치, axis=1), 1.0)
    문장표현 = 합계 / 유효자리수

    안내문점수 = keras.layers.Dense(len(안내문), activation="softmax",
                                    name="guide_scores")(문장표현)

    모델 = keras.Model(문의입력, 안내문점수)
    관찰모델 = keras.Model(문의입력, [안내문점수, 어텐션점수])
    return 모델, 관찰모델


