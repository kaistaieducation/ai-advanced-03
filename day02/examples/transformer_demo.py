def 평가결과보기(보기개수=2):
    """연습에 쓰지 않은 문의 전체를 넣어 보고, 세 종류의 사례를 보여 줍니다."""
    _확인됨()
    문의들 = _상태["평가문의"]
    정답 = _상태["평가정답"]
    순위, 점수 = _모델순위(문의들)

    맞음 = 순위[:, 0] == 정답
    정렬 = np.sort(점수, axis=1)
    점수차 = 정렬[:, -1] - 정렬[:, -2]

    print("교육용으로 만든 처음 보는 문의 %d개를 한꺼번에 넣어 보았습니다." % len(문의들))
    print("그중 1위 후보가 사람 판단과 같았던 경우 : %d개" % int(맞음.sum()))
    print()

    def _고르기(정렬순서, 쓸수있음):
        """미리 정한 순서대로 고르되, 사람 판단이 같은 문의는 한 번만 보여 줍니다."""
        고른것, 나온라벨 = [], set()
        for i in 정렬순서:
            if not 쓸수있음[i] or 정답[i] in 나온라벨:
                continue
            고른것.append(i)
            나온라벨.add(정답[i])
            if len(고른것) == 보기개수:
                break
        return 고른것

    뚜렷 = _고르기(np.argsort(-점수차), 맞음)      # 맞았고 1·2위 차이가 큰 순서
    비슷 = _고르기(np.argsort(점수차), 맞음)       # 맞았지만 1·2위 차이가 작은 순서
    틀림 = _고르기(np.argsort(-점수차), ~맞음)     # 틀린 것

    묶음 = [("■ 결과가 뚜렷하게 갈린 예", 뚜렷),
            ("■ 1·2위 결과가 비슷했던 예", 비슷),
            ("■ 틀린 예", 틀림)]
    for 이름, 목록 in 묶음:
        print(이름)
        if len(목록) == 0:
            print("    (이번 실행에서는 해당 사례가 없습니다.)")
            print()
            continue
        for i in 목록:
            print("  %s%s" % (_폭맞춤("문의", 12), 문의들[i]))
            print("  %s%s" % (_폭맞춤("사람 판단", 12), 제목[정답[i]]))
            _후보출력(순위[i])
            print()

    print("'1·2위가 비슷했던 예' 는 이번 모델의 출력 1위와 2위가 가깝게 나왔다는")
    print("교육용 분류입니다. 실제 정답 확률을 뜻하지 않습니다.")
    return None


